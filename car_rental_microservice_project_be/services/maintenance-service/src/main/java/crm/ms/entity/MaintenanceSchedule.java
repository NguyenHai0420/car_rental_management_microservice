package crm.ms.entity;

import crm.ms.enums.MaintenanceStatus;
import crm.ms.enums.Priority;
import jakarta.persistence.*;
import lombok.*;

import java.math.BigDecimal;
import java.time.Instant;
import java.time.LocalDate;
import java.time.LocalDateTime;
import java.time.ZoneOffset;
import java.util.ArrayList;
import java.util.List;
import java.util.UUID;

/**
 * Lịch bảo dưỡng cụ thể cho từng xe — Aggregate Root.
 * State machine: SCHEDULED / OVERDUE → START_REQUESTED → IN_PROGRESS → COMPLETE_REQUESTED → COMPLETED
 *                                    → CANCELLED (từ SCHEDULED hoặc OVERDUE)
 */
@Entity
@Table(name = "maintenance_schedules", indexes = {
        @Index(name = "idx_msched_vehicle", columnList = "vehicle_id"),
        @Index(name = "idx_msched_standard", columnList = "standard_id"),
        @Index(name = "idx_msched_status", columnList = "status"),
        @Index(name = "idx_msched_scheduled", columnList = "scheduled_date"),
        @Index(name = "idx_msched_overdue", columnList = "status, due_date"),
        @Index(name = "idx_msched_vehicle_interval", columnList = "vehicle_id, status, scheduled_start_at, scheduled_end_at"),
        @Index(name = "idx_msched_sync_pending", columnList = "status, sync_exhausted, next_sync_attempt_at")
})
@Getter
@Setter
@NoArgsConstructor
@AllArgsConstructor
@Builder
public class MaintenanceSchedule {

    @Id
    @GeneratedValue(strategy = GenerationType.UUID)
    @Column(nullable = false, updatable = false)
    private UUID id;

    /** Reference to Vehicle Service — NOT a FK (cross-service) */
    @Column(name = "vehicle_id", nullable = false)
    private UUID vehicleId;

    @ManyToOne(fetch = FetchType.LAZY)
    @JoinColumn(name = "standard_id", nullable = true, foreignKey = @ForeignKey(name = "fk_msched_standard"))
    private MaintenanceStandard standard;

    @Enumerated(EnumType.STRING)
    @Column(nullable = false, length = 25)
    @Builder.Default
    private MaintenanceStatus status = MaintenanceStatus.SCHEDULED;

    /** Chuẩn hóa khoảng thời gian bảo trì nửa mở [scheduledStartAt, scheduledEndAt) theo UTC */
    @Column(name = "scheduled_start_at", nullable = false)
    private Instant scheduledStartAt;

    @Column(name = "scheduled_end_at", nullable = false)
    private Instant scheduledEndAt;

    @Column(name = "scheduled_date", nullable = false)
    private LocalDate scheduledDate;

    /** Mốc km dự kiến bảo dưỡng */
    @Column(name = "scheduled_at_km", precision = 10, scale = 1)
    private BigDecimal scheduledAtKm;

    /** Hạn chót phải hoàn thành */
    @Column(name = "due_date")
    private LocalDate dueDate;

    @Column(name = "started_date")
    private LocalDate startedDate;

    @Column(name = "started_at")
    private Instant startedAt;

    @Column(name = "completed_date")
    private LocalDate completedDate;

    @Column(name = "completed_at")
    private Instant completedAt;

    /** Số km thực tế khi hoàn thành */
    @Column(name = "completed_at_km", precision = 10, scale = 1)
    private BigDecimal completedAtKm;

    @Column(name = "estimated_cost", precision = 12, scale = 2)
    private BigDecimal estimatedCost;

    @Column(name = "actual_cost", precision = 12, scale = 2)
    private BigDecimal actualCost;

    /** Kỹ thuật viên / xưởng phụ trách */
    @Column(name = "assigned_to", length = 100)
    private String assignedTo;

    @Enumerated(EnumType.STRING)
    @Column(nullable = false, length = 10)
    @Builder.Default
    private Priority priority = Priority.MEDIUM;

    @Column(columnDefinition = "TEXT")
    private String notes;

    @Column(name = "cancellation_reason", length = 500)
    private String cancellationReason;

    /** Trạng thái trước khi thực hiện Saga sync sang Vehicle Service (dùng cho compensating revert) */
    @Enumerated(EnumType.STRING)
    @Column(name = "pre_sync_status", length = 25)
    private MaintenanceStatus preSyncStatus;

    /** Trạng thái thực tế của xe do Vehicle Service quyết định và trả về sau khi đồng bộ */
    @Column(name = "resolved_vehicle_status", length = 30)
    private String resolvedVehicleStatus;

    /** Khóa idempotency cho lệnh đồng bộ trạng thái xe sang Vehicle Service */
    @Column(name = "sync_request_id")
    private UUID syncRequestId;

    @Column(name = "sync_retry_count", nullable = false)
    @Builder.Default
    private Integer syncRetryCount = 0;

    @Column(name = "next_sync_attempt_at")
    private Instant nextSyncAttemptAt;

    @Column(name = "last_sync_error", length = 500)
    private String lastSyncError;

    @Column(name = "sync_exhausted", nullable = false)
    @Builder.Default
    private Boolean syncExhausted = false;

    /** 1 = tạo tự động từ event VehicleAdded */
    @Column(name = "is_auto_generated", nullable = false)
    @Builder.Default
    private Boolean isAutoGenerated = false;

    @Version
    @Column(nullable = false)
    @Builder.Default
    private Long version = 0L;

    @Column(name = "created_at", nullable = false, updatable = false)
    private LocalDateTime createdAt;

    @Column(name = "updated_at", nullable = false)
    private LocalDateTime updatedAt;

    @Column(name = "created_by", length = 100)
    private String createdBy;

    @OneToMany(mappedBy = "schedule", cascade = CascadeType.ALL)
    @Builder.Default
    private List<ServiceRecord> serviceRecords = new ArrayList<>();

    @OneToMany(mappedBy = "schedule", cascade = CascadeType.ALL, orphanRemoval = true)
    @Builder.Default
    private List<InspectionChecklist> inspectionChecklists = new ArrayList<>();

    @PrePersist
    protected void onCreate() {
        syncLegacyDatesFromUtcInterval();
        LocalDateTime nowUtc = LocalDateTime.now(ZoneOffset.UTC);
        createdAt = nowUtc;
        updatedAt = nowUtc;
    }

    @PreUpdate
    protected void onUpdate() {
        syncLegacyDatesFromUtcInterval();
        updatedAt = LocalDateTime.now(ZoneOffset.UTC);
    }

    private void syncLegacyDatesFromUtcInterval() {
        if (scheduledStartAt != null) {
            scheduledDate = scheduledStartAt.atZone(ZoneOffset.UTC).toLocalDate();
        }
        if (scheduledEndAt != null) {
            dueDate = scheduledEndAt.atZone(ZoneOffset.UTC).toLocalDate();
        }
    }
}
