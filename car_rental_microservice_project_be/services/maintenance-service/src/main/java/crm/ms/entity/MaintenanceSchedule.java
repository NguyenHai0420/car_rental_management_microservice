package crm.ms.entity;

import crm.ms.enums.MaintenanceStatus;
import crm.ms.enums.Priority;
import jakarta.persistence.*;
import lombok.*;

import java.math.BigDecimal;
import java.time.LocalDate;
import java.time.LocalDateTime;
import java.util.ArrayList;
import java.util.List;
import java.util.UUID;

/**
 * Lịch bảo dưỡng cụ thể cho từng xe — Aggregate Root.
 * State machine: SCHEDULED → IN_PROGRESS → COMPLETED
 *                           → OVERDUE (nếu quá hạn)
 *                           → CANCELLED
 */
@Entity
@Table(name = "maintenance_schedules", indexes = {
        @Index(name = "idx_msched_vehicle", columnList = "vehicle_id"),
        @Index(name = "idx_msched_standard", columnList = "standard_id"),
        @Index(name = "idx_msched_status", columnList = "status"),
        @Index(name = "idx_msched_scheduled", columnList = "scheduled_date"),
        @Index(name = "idx_msched_overdue", columnList = "status, due_date")
})
@Getter
@Setter
@NoArgsConstructor
@AllArgsConstructor
@Builder
public class MaintenanceSchedule {

    @Id
    @GeneratedValue(strategy = GenerationType.UUID)
    @Column(nullable = false, updatable = false)
    private UUID id;

    /** Reference to Vehicle Service — NOT a FK (cross-service) */
    @Column(name = "vehicle_id", nullable = false)
    private UUID vehicleId;

    @ManyToOne(fetch = FetchType.LAZY)
    @JoinColumn(name = "standard_id", nullable = false, foreignKey = @ForeignKey(name = "fk_msched_standard"))
    private MaintenanceStandard standard;

    @Enumerated(EnumType.STRING)
    @Column(nullable = false, length = 15)
    private MaintenanceStatus status = MaintenanceStatus.SCHEDULED;

    @Column(name = "scheduled_date", nullable = false)
    private LocalDate scheduledDate;

    /** Mốc km dự kiến bảo dưỡng */
    @Column(name = "scheduled_at_km", precision = 10, scale = 1)
    private BigDecimal scheduledAtKm;

    /** Hạn chót phải hoàn thành */
    @Column(name = "due_date")
    private LocalDate dueDate;

    @Column(name = "started_date")
    private LocalDate startedDate;

    @Column(name = "completed_date")
    private LocalDate completedDate;

    /** Số km thực tế khi hoàn thành */
    @Column(name = "completed_at_km", precision = 10, scale = 1)
    private BigDecimal completedAtKm;

    @Column(name = "estimated_cost", precision = 12, scale = 2)
    private BigDecimal estimatedCost;

    @Column(name = "actual_cost", precision = 12, scale = 2)
    private BigDecimal actualCost;

    /** Kỹ thuật viên / xưởng phụ trách */
    @Column(name = "assigned_to", length = 100)
    private String assignedTo;

    @Enumerated(EnumType.STRING)
    @Column(nullable = false, length = 10)
    private Priority priority = Priority.MEDIUM;

    @Column(columnDefinition = "TEXT")
    private String notes;

    /** 1 = tạo tự động từ event VehicleAdded */
    @Column(name = "is_auto_generated", nullable = false)
    private Boolean isAutoGenerated = false;

    @Column(name = "created_at", nullable = false, updatable = false)
    private LocalDateTime createdAt;

    @Column(name = "updated_at", nullable = false)
    private LocalDateTime updatedAt;

    @Column(name = "created_by", length = 100)
    private String createdBy;

    @OneToMany(mappedBy = "schedule", cascade = CascadeType.ALL)
    @Builder.Default
    private List<ServiceRecord> serviceRecords = new ArrayList<>();

    @OneToMany(mappedBy = "schedule", cascade = CascadeType.ALL, orphanRemoval = true)
    @Builder.Default
    private List<InspectionChecklist> inspectionChecklists = new ArrayList<>();

    @PrePersist
    protected void onCreate() {
        createdAt = LocalDateTime.now();
        updatedAt = LocalDateTime.now();
    }

    @PreUpdate
    protected void onUpdate() {
        updatedAt = LocalDateTime.now();
    }
}
